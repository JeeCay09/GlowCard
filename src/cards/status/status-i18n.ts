export type StatusKey = keyof typeof de;

export function isStatusKey(k: string): k is StatusKey {
  return k in de;
}

/** Status text with `{placeholders}` filled in. */
export function st(
  hass: HomeAssistant | undefined,
  key: StatusKey,
  vars: Record<string, string | number> = {},
): string {
  const dict = language(hass).startsWith('de') ? de : en;
  return dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
